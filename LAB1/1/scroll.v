// [教學註解] 功能：循環移位暫存器：在時脈觸發時移動位元圖樣，用於 LED 跑馬燈/移位效果。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module scroll (clk, reset, shift_out);
// [教學註解] 輸入埠：clk=系統時脈；reset=系統重置。
input 	clk, reset;
// [教學註解] 輸出埠：shift_out=移位暫存器輸出。
output	[7:0]shift_out;
// [教學註解] 程序賦值暫存型訊號(reg)：shift_out=移位暫存器輸出。
reg		[7:0]shift_out;
// [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
always@ (posedge clk or posedge reset)
begin
	// [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
	if(reset)
		shift_out= 8'b1100_0000;
	else
		// [教學註解] 串接運算 { } 重新排列位元，可用來實作移位或把多個欄位合併成一個匯流排。
		shift_out= {shift_out[0], shift_out[7:1]};
	end
endmodule
