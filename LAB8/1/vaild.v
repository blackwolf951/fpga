// 檔名: vaild.v (依專案命名沿用 vaild 拼法，對應 lab6_debounce_ctl.v)
// 【狀態：學生已自行完成，邏輯正確，僅補充註解】
// 功能: 按鍵去彈跳(debounce) + 產生單一有效脈波
//       用一個 6-bit 移位暫存器把 press 訊號連續取樣6次，
//       只要 press 已經連續保持1超過5個clk(gg[5]變成1)，就不再視為新的按鍵事件，
//       避免「按住不放」時被誤判成連續多次按鍵
// 注意: 這裡的 clk 建議接「分頻後的慢速時脈 ck」，而不是快速原始時脈，
//       因為機械按鍵彈跳(bounce)通常會持續數毫秒，
//       如果clk太快，6個clk週期可能遠小於1毫秒，濾波效果會不夠。
// ============================================================

// ============================================================================
// [教學註解] 檔案：vaild.v
// [教學註解] 模組：vaild
// [教學註解] 功能：按鍵有效訊號產生器：利用連續取樣/移位方式抑制彈跳並輸出有效按鍵脈波。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module vaild (clk, rst, press, press_valid);
    // [教學註解] 輸入埠：press=按鍵是否被偵測；clk=系統時脈；rst=系統重置。
    input press, clk, rst;
    // [教學註解] 輸出埠：press_valid=去彈跳後的有效按鍵脈波。
    output press_valid;
    // [教學註解] 程序賦值暫存型訊號(reg)：宣告此區塊中使用的訊號與位元寬度。
    reg [5:0] gg;

    // press_valid = 1，代表：目前正在按(press=1) 且 尚未被判定為「已持續按住」(gg[5]=0)
    // [教學註解] 連續指定(assign)：描述組合邏輯連線，右式改變時左式會立即重新計算。
    assign press_valid = ~(gg[5] || (~press));

    // [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
    always@(posedge clk or posedge rst) begin
        // [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
        if(rst)
            gg <= 6'b0;                 // 重置移位暫存器
        else
            // [教學註解] 串接運算 { } 重新排列位元，可用來實作移位或把多個欄位合併成一個匯流排。
            gg <= {gg[4:0], press};     // 每個clk把新的press值移入最低位元
    end
endmodule
