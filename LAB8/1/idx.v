// 檔名: idx.v   【狀態：投影片已給完整程式碼，邏輯正確，僅補充註解】
// 功能: 每個 clk 上升緣，idx(0~7,3bit) 加1，同時 row(8bit one-hot) 也跟著循環右移一位，
//       兩者是同步的：idx 用來當地圖(map.v)的列位址，row 用來實際驅動8x8點矩陣的列選擇線
// 注意: 頂層模組呼叫這個模組時，clk 建議接「快速時脈」(FPGA原始時脈，例如50MHz)，
//       不要接分頻後的慢速時脈 ck。
//       因為 row 同時也是拿去驅動 LED 硬體做「多工掃描(multiplexing)」用的，
//       掃描速度必須夠快(每一列切換要在人眼殘影時間內完成一輪8列)，
//       否則畫面會出現閃爍或某幾列偏暗的情況。
// ============================================================

// ============================================================================
// [教學註解] 檔案：idx.v
// [教學註解] 模組：idx
// [教學註解] 功能：8×8 LED 掃描索引器：循環產生 idx 與對應 row，使各列快速輪流顯示。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module  idx(clk, reset, idx, row);
// [教學註解] 輸入埠：reset=系統重置；clk=系統時脈。
input        reset, clk;
// [教學註解] 輸出埠：idx=目前掃描列索引。
output reg  [2:0]idx;
// [教學註解] 輸出埠：row=8×8 列掃描訊號。
output reg  [7:0]row;
// [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
always@(posedge clk or posedge reset)
begin
    // [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
    if(reset) begin
        idx<=3'b000;
        row<=8'b1000_0000;
    end
    else begin
        idx<=idx+3'b001;
        // [教學註解] 串接運算 { } 重新排列位元，可用來實作移位或把多個欄位合併成一個匯流排。
        row<={row[0],row[7:1]};   // 把最低位元轉到最高位元，其餘右移一位 -> 循環右移
    end
end
endmodule
