// ============================================================================
// [教學註解] 檔案：shift.v
// [教學註解] 模組：shift
// [教學註解] 功能：位置移位暫存器：依左右/上下控制讓 one-hot 位置位元移動，並可被 reset/unable 控制。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module  shift(left, right, reset, unable, out, clk);
// [教學註解] 輸入埠：left=左移控制；right=右移控制；reset=系統重置；clk=系統時脈；unable=禁止移動控制。
input       left, right, reset, clk, unable;
// [教學註解] 輸出埠：宣告此區塊中使用的訊號與位元寬度。
output reg  [7:0]out;

// [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
always@(posedge clk or posedge reset)
begin
    // [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
    if(reset)
        out<=8'b0000_1000;        // 重置到畫面中間位置(正確，投影片已給)
    else if(unable)        //碰撞狀態
        out<=8'b0000_0000;        // 撞牆後熄滅紅點(正確，投影片已給)
    else if(left)
        // --------------------------------------------------
        // 原本: ~~~your code~~~   ← 缺少程式碼，未賦值
        // 說明: 依投影片第6頁範例，原本 0000_1000 按左會變成 0001_0000，
        //       表示 one-hot 的位元往「高位(MSB)」方向移動一位
        // --------------------------------------------------
        out <= {out[6:0], 1'b0};   // 位元往左(MSB方向)移一位
    else if(right)
        // --------------------------------------------------
        // 原本: ~~~your code~~~   ← 缺少程式碼，未賦值
        // 說明: 依投影片第6頁範例，原本 0000_1000 按右會變成 0000_0100，
        //       表示 one-hot 的位元往「低位(LSB)」方向移動一位
        // --------------------------------------------------
        out <= {1'b0, out[7:1]};   // 位元往右(LSB方向)移一位
    else
        out<=out;                  // 沒有按鍵時維持原位置(正確，投影片已給)
end
endmodule
