// ============================================================
// 檔名: map.v （已修正）
// 問題: 原本 4'd4 = 8'b1010_1111，紅點的起始位置 hor=ver=8'b0000_1000
//       剛好對到這一列的牆壁位元(=1)，導致一開機/一放開reset就立刻判定撞牆，
//       畫面變成全綠色的 coll=1 地圖(8'hFF)，且紅點被 unable 訊號熄滅。
// 修正: 重新設計地圖，四周圍牆，中間留通道，並且特別確保
//       第4列(idx=4)、第5個bit(對應hor/ver初始值0000_1000)是通道(0)，
//       紅點才不會一出生就疊在牆上。
// ============================================================
module      map(addr,data);
input       [3:0]addr;
output reg  [7:0]data;
always@(addr)
begin
case(addr)
    // 正常地圖 (coll=0)：1=牆壁, 0=通道
    // bit順序(左到右) = column 0~7，第4行(第5個bit, index4)在下面特別保留0
    4'd0    :data=8'b1111_1111;   // 第0列：上邊界，全部是牆
    4'd1    :data=8'b1000_0001;   // 通道
    4'd2    :data=8'b1011_1101;   // 障礙(第4個bit=1,不影響起點列)
    4'd3    :data=8'b1010_0001;   // 通道
    4'd4    :data=8'b1000_0001;   // ★起始列：第5個bit(index4)保留為0，紅點才不會一出生就撞牆
    4'd5    :data=8'b1011_1101;   // 障礙
    4'd6    :data=8'b1000_0001;   // 通道
    4'd7    :data=8'b1111_1111;   // 第7列：下邊界，全部是牆

    // 撞牆後顯示全亮(coll=1)
    4'd8    :data=8'b1111_1111;
    4'd9    :data=8'b1111_1111;
    4'd10   :data=8'b1111_1111;
    4'd11   :data=8'b1111_1111;
    4'd12   :data=8'b1111_1111;
    4'd13   :data=8'b1111_1111;
    4'd14   :data=8'b1111_1111;
    4'd15   :data=8'b1111_1111;
    default :data=8'b0000_0000;
endcase
end
endmodule
