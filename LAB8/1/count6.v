// 檔名: count6.v   【狀態：學生已自行完成，邏輯正確，僅補充註解】
// 功能: 產生 3-bit 掃描線 sel，依序輸出 000->001->010->011->100->101 後歸零，
//       共6個狀態(對應數字鍵盤的行掃描)，這個 sel 同時要送到:
//       (1) 頂層輸出腳位 sel[2:0]，去驅動實體鍵盤硬體的掃描線
//       (2) key_decode.v 的 sel 輸入，讓解碼邏輯知道現在掃到第幾條線
// 注意: 建議由分頻後的慢速時脈 ck 驅動(和 vaild.v 同一個時脈域)，
//       如果直接用快速原始時脈，sel 切換太快可能造成鍵盤硬體訊號還沒穩定就被讀取。
// ============================================================

// ============================================================================
// [教學註解] 檔案：count6.v
// [教學註解] 模組：count6
// [教學註解] 功能：6 狀態掃描計數器：循環產生多位顯示器或鍵盤掃描的選擇訊號。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module count6(clk, rst, sel);
    // [教學註解] 輸入埠：clk=系統時脈；rst=系統重置。
    input clk, rst;
    // [教學註解] 輸出埠：sel=掃描選擇訊號。
    output reg [2:0] sel;

    // 用一個計數器循環：000 -> 001 -> 010 -> 011 -> 100 -> 101 的六種掃描狀態
    // [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
    always @(posedge clk or posedge rst) begin
        // [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
        if (rst)
            sel <= 3'b000;
        else if (sel == 3'b101)
            sel <= 3'b000;      // 掃描完6行就從頭開始
        else
            // [教學註解] 計數 +1：每次有效時脈事件讓目前數值增加一。
            sel <= sel + 1'b1;  // 每次觸發時脈就換下一行
    end
endmodule
