// 檔名: mix.v   【狀態：assign red 原本空白 -> 已修正】
// 功能: 把「目前掃描列 row」與「紅點所在列 ver」比對，
//       如果目前掃描的列正好是紅點所在的那一列，就把 hor(紅點所在的行)輸出到 red，
//       否則這一列不用畫紅點，輸出全 0
// ============================================================

// ============================================================================
// [教學註解] 檔案：mix.v
// [教學註解] 模組：mix
// [教學註解] 功能：紅點畫面合成器：將水平與垂直位置和目前掃描列比對，產生 red 點陣資料。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module  mix(ver, hor, row, red);
// [教學註解] 輸入埠：ver=紅點垂直 one-hot 位置；hor=紅點水平 one-hot 位置；row=8×8 列掃描訊號。
input       [7:0]ver, hor, row;
// [教學註解] 輸出埠：red=8×8 紅色點陣資料。
output  [7:0]red;

// --------------------------------------------------------
// 原本: assign red=~~~your code~~~   ← 缺少程式碼，未賦值
// 說明: ver、row 都是 one-hot(只有1個位元是1)，(row & ver)!=0 代表兩者位置相同，
//       也就是「現在掃描到的列」正好是「紅點所在的列」，這時才要把 hor 顯示出來，
//       其餘列則輸出全0(不顯示紅點)。可對照投影片第15頁的表格驗證:
//       row=0010_0000 且 ver=0010_0000 時 -> red=hor=0001_0000；其餘列 red=0
// --------------------------------------------------------
// [教學註解] 連續指定(assign)搭配 ?: 條件運算子，描述純組合邏輯，不需要時脈。
assign  red = ((row & ver) != 8'b0) ? hor : 8'b0000_0000;

endmodule
