// 功能: 偵測目前掃描到的紅點(red)是否與牆壁(green)重疊 -> 判斷撞牆
// 注意: 頂層模組呼叫這個模組時，clk 必須接「快速時脈」(和 idx.v 同一顆)，
//       不能接分頻後的慢速時脈 ck，否則 red 訊號只在極短暫的瞬間才會非0，
//       慢速時脈很容易「取樣不到」，導致永遠偵測不到撞牆。
// ============================================================

// ============================================================================
// [教學註解] 檔案：collision.v
// [教學註解] 模組：collision
// [教學註解] 功能：碰撞偵測器：檢查 red 與 green 是否有同一位元同時為 1，並鎖存碰撞狀態。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module  collision(clk, reset, red, green, coll);
// [教學註解] 輸入埠：clk=系統時脈；reset=系統重置。
input       clk, reset;
// [教學註解] 輸入埠：red=8×8 紅色點陣資料；green=8×8 綠色點陣資料。
input       [7:0]red, green;
// [教學註解] 輸出埠：coll=碰撞狀態。
output reg  coll;
// [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
always@(posedge clk or posedge reset)
begin
    // [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
    if(reset)
        coll<=1'b0;
    else if((red & green) != 8'b0)    //發生碰撞：紅點所在的位元與牆壁位元同時為1
        coll<=1'b1;
    else
        coll<=coll;   // 說明：coll 一旦變成1就會鎖住(latch)，直到reset才會清除
                       // 這是刻意設計：撞牆後畫面凍結，需要按reset才能重新開始
end
endmodule
