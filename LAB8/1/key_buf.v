// ============================================================
// 檔名: key_buf.v （已修正）
// 功能: 當 press_valid 有效脈波出現時，把 scan_code 鎖存(latch)成 keycode，
//       供 move.v 判斷目前要往哪個方向移動
// 修正重點:
//   原本 else 分支寫 keycode<=keycode(保持上一次的值)，
//   會造成「按一下某個方向鍵，之後永遠不會停」，因為 keycode 永遠不會
//   回到代表「沒有按鍵」的 1111。
//   改成 else 時回到 4'b1111，這樣紅點只有在偵測到新的有效按鍵事件時才會走，
//   放開按鍵之後(沒有新的 press_valid)就會停下來。
// ============================================================

// ============================================================================
// [教學註解] 檔案：key_buf.v
// [教學註解] 模組：key_buf
// [教學註解] 功能：按鍵緩衝暫存器：只在有效按鍵事件發生時更新並保存鍵碼。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module key_buf(clk, rst, press_valid, scan_code, keycode);
    // [教學註解] 輸入埠：clk=系統時脈；rst=系統重置；press_valid=去彈跳後的有效按鍵脈波。
    input clk, rst, press_valid;
    // [教學註解] 輸入埠：scan_code=掃描解出的按鍵碼。
    input [3:0] scan_code;
    // [教學註解] 輸出埠：keycode=鎖存後的按鍵碼。
    output reg [3:0] keycode;

    // [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
    always@(posedge clk or posedge rst) begin
        // [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
        if(rst)
            keycode <= 4'b1111;              // 重置為「沒有鍵被按下」的碼
        // [教學註解] 只有確認為有效按鍵事件時才更新鍵碼，避免雜訊或彈跳造成重複寫入。
        else if(press_valid)
            keycode <= scan_code;            // 偵測到有效按鍵才更新keycode
        else
            keycode <= 4'b1111;              // 沒有新的按鍵事件 -> 回到無按鍵，紅點停止
    end
endmodule
