// [逐行教學 L001][語法] `module` 宣告一個硬體模組；模組名稱後括號列出對外 I/O。
// [逐行教學 L001][用途] 水平位移索引產生器。。
module idx_gen(clk, rst, idx);
// [逐行教學 L002][語法] `input` 宣告由外部進入模組的輸入埠。
// [逐行教學 L002][用途] 本段宣告：clk=系統時脈；rst=重置。
    input clk, rst;
// [逐行教學 L003][語法] `output` 宣告由模組送到外部的輸出埠；`[6:0]` 指定位元範圍。
// [逐行教學 L003][用途] 本段宣告：idx=位移索引。
    output [6:0] idx;
// [逐行教學 L004][語法] `reg` 宣告可在 `always/function` 中賦值的程序變數；是否形成 DFF 由 always 類型決定；`[6:0]` 指定位元範圍。
// [逐行教學 L004][用途] 本段宣告：idx=位移索引。
    reg [6:0] idx;
// [逐行教學 L005][語法] 空白行沒有 Verilog 語法作用；它只負責排版與區隔程式區塊。
// [逐行教學 L005][用途] 把不同功能區塊視覺上分開，方便閱讀。
    
// [逐行教學 L006][語法] `always @(posedge/negedge ...)` 是邊緣觸發的時序程序區塊；監看 clk 的上升緣、rst 的上升緣；同一行的 `begin` 開始一個多敘述區塊。
// [逐行教學 L006][用途] 通常綜合成 DFF/暫存器，在指定邊緣更新狀態；Reset 也在敏感度表，因此是非同步重置。
    always @(posedge clk or posedge rst) begin
// [逐行教學 L007][語法] `if (rst)` 是條件分支：條件為 1 才執行後續敘述。
// [逐行教學 L007][用途] 檢查 `rst` 以決定資料/狀態要走哪一條路徑；這是重置分支。
        if (rst)
// [逐行教學 L008][語法] `idx <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`7'd0` = 7-bit 十進位常數。
// [逐行教學 L008][用途] 更新 `idx`（位移索引），下一值由 `7'd0` 計算。
            idx <= 7'd0;
// [逐行教學 L009][語法] `if (idx == 7'd88)` 是條件分支：條件為 1 才執行後續敘述；`else if` 只在前面 if 不成立時繼續測試下一個條件；`else if(...)` 是子模組實例化；`if`
// [逐行教學 L009][語法] 是這一顆硬體實例名稱；`7'd88` = 7-bit 十進位常數；`==` 是相等比較，結果為 1 或 0。
// [逐行教學 L009][用途] 檢查 `idx == 7'd88` 以決定資料/狀態要走哪一條路徑；把 `else` 子模組放進目前模組並與內部訊號連線。
        else if (idx == 7'd88) // 總共 11 個字 × 8欄 = 88 欄，跑到尾端時歸零循環
// [逐行教學 L010][語法] `idx <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`7'd0` = 7-bit 十進位常數。
// [逐行教學 L010][用途] 更新 `idx`（位移索引），下一值由 `7'd0` 計算。
            idx <= 7'd0;
// [逐行教學 L011][語法] `else` 是前面條件都不成立時執行的備援分支。
// [逐行教學 L011][用途] 完成目前模組資料路徑或控制流程中的一個步驟。
        else
// [逐行教學 L012][語法] `idx <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`7'd1` = 7-bit 十進位常數。
// [逐行教學 L012][用途] 更新 `idx`（位移索引），下一值由 `idx + 7'd1` 計算。
            idx <= idx + 7'd1; // 每個慢速時脈向左移動 1 個欄位像素
// [逐行教學 L013][語法] `end` 結束最近一個 `begin` 區塊。
// [逐行教學 L013][用途] 關閉目前條件、時序或組合邏輯區塊。
    end
// [逐行教學 L014][語法] `endmodule` 與前面的 `module` 配對，結束模組定義。
// [逐行教學 L014][用途] 結束 `idx_gen` 的 RTL 描述。
endmodule