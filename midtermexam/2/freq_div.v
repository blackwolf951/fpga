// [逐行教學 HEADER] 每一個「原始實體行」前都加入 [語法] + [用途]，原始程式行本身不修改。
// [逐行教學 HEADER] 若一個原始行塞了多個敘述，註解會把同一行內的宣告/賦值/子模組一起拆解說明。
// [逐行教學 HEADER] ===============================================================
// [逐行教學 L001][語法] `module` 宣告一個硬體模組；模組名稱後括號列出對外 I/O。
// [逐行教學 L001][用途] 時脈分頻器：利用二進位計數器的某一位，把 FPGA 高速系統時脈降成較慢時脈。。
module freq_div(clk_in, reset, clk_out);
// [逐行教學 L002][語法] `parameter` 宣告可在實例化時覆寫的常數參數。
// [逐行教學 L002][用途] 本段宣告：exp。
    parameter exp = 20;   
// [逐行教學 L003][語法] `input` 宣告由外部進入模組的輸入埠。
// [逐行教學 L003][用途] 本段宣告：clk_in=輸入時脈；reset=重置。
    input clk_in, reset;
// [逐行教學 L004][語法] `output` 宣告由模組送到外部的輸出埠。
// [逐行教學 L004][用途] 本段宣告：clk_out=分頻後時脈。
    output clk_out;
// [逐行教學 L005][語法] 空白行沒有 Verilog 語法作用；它只負責排版與區隔程式區塊。
// [逐行教學 L005][用途] 把不同功能區塊視覺上分開，方便閱讀。
    
// [逐行教學 L006][語法] `reg` 宣告可在 `always/function` 中賦值的程序變數；是否形成 DFF 由 always 類型決定；`[exp-1:0]` 指定位元範圍。
// [逐行教學 L006][用途] 本段宣告：divider=分頻計數器。
    reg [exp-1:0] divider;
// [逐行教學 L007][語法] 空白行沒有 Verilog 語法作用；它只負責排版與區隔程式區塊。
// [逐行教學 L007][用途] 把不同功能區塊視覺上分開，方便閱讀。
    
// [逐行教學 L008][語法] `assign 左式 = 右式;` 是 continuous assignment；這裡的 `=` 屬連續指定，不是 always 內的阻塞賦值；`[msb:lsb]`/`[index]`
// [逐行教學 L008][語法] 用來選取向量的一段或單一 bit。
// [逐行教學 L008][用途] 更新 `clk_out`（分頻後時脈），下一值由 `divider[exp-1]` 計算；右式一變化就立即重新驅動左側 wire。
    assign clk_out = divider[exp-1];
// [逐行教學 L009][語法] 空白行沒有 Verilog 語法作用；它只負責排版與區隔程式區塊。
// [逐行教學 L009][用途] 把不同功能區塊視覺上分開，方便閱讀。
    
// [逐行教學 L010][語法] `always @(posedge/negedge ...)` 是邊緣觸發的時序程序區塊；監看 clk_in 的上升緣、reset 的上升緣；同一行的 `begin` 開始一個多敘述區塊。
// [逐行教學 L010][用途] 通常綜合成 DFF/暫存器，在指定邊緣更新狀態；Reset 也在敏感度表，因此是非同步重置。
    always @(posedge clk_in or posedge reset) begin
// [逐行教學 L011][語法] `if (reset)` 是條件分支：條件為 1 才執行後續敘述。
// [逐行教學 L011][用途] 檢查 `reset` 以決定資料/狀態要走哪一條路徑；這是重置分支。
        if (reset)
// [逐行教學 L012][語法] `divider <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新。
// [逐行教學 L012][用途] 更新 `divider`（分頻計數器）為 0/關閉或初始值。
            divider <= 0; // 改用 <= 且直接給 0 即可清空
// [逐行教學 L013][語法] `else` 是前面條件都不成立時執行的備援分支。
// [逐行教學 L013][用途] 完成目前模組資料路徑或控制流程中的一個步驟。
        else
// [逐行教學 L014][語法] `divider <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`1'b1` = 1-bit 二進位常數。
// [逐行教學 L014][用途] 更新 `divider`（分頻計數器）為舊值 +1，完成向上計數。
            divider <= divider + 1'b1; // 循序邏輯請一律使用 <=
// [逐行教學 L015][語法] `end` 結束最近一個 `begin` 區塊。
// [逐行教學 L015][用途] 關閉目前條件、時序或組合邏輯區塊。
    end
// [逐行教學 L016][語法] `endmodule` 與前面的 `module` 配對，結束模組定義。
// [逐行教學 L016][用途] 結束 `freq_div` 的 RTL 描述。
endmodule