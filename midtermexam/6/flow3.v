// [逐行教學 L001][語法] `module` 宣告一個硬體模組；模組名稱後括號列出對外 I/O；埠列表直接出現 `input/output`，屬 ANSI-style 埠宣告；`[msb:lsb]`/`[index]`
// [逐行教學 L001][語法] 用來選取向量的一段或單一 bit。
// [逐行教學 L001][用途] 三段流水圖樣核心。。
module flow3(input clk,input reset,input tick_move,input enable,output reg [2:0] pos,output reg direction_down);
// [逐行教學 L002][語法] `always @(posedge/negedge ...)` 是邊緣觸發的時序程序區塊；監看 clk 的上升緣、reset 的上升緣；同一行的 `begin` 開始一個多敘述區塊。
// [逐行教學 L002][用途] 通常綜合成 DFF/暫存器，在指定邊緣更新狀態；Reset 也在敏感度表，因此是非同步重置。
 always @(posedge clk or posedge reset) begin
// [逐行教學 L003][語法] `if (reset)` 是條件分支：條件為 1 才執行後續敘述；`pos <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`direction_down <=
// [逐行教學 L003][語法] ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`1'b1` = 1-bit 二進位常數。
// [逐行教學 L003][用途] 檢查 `reset` 以決定資料/狀態要走哪一條路徑；這是重置分支；更新 `pos`為 0/關閉或初始值；更新 `direction_down`，下一值由 `1'b1` 計算。
  if(reset) begin pos<=0;direction_down<=1'b1;end
// [逐行教學 L004][語法] `if (tick_move && enable)` 是條件分支：條件為 1 才執行後續敘述；`else if` 只在前面 if 不成立時繼續測試下一個條件；`else if(...)`
// [逐行教學 L004][語法] 是子模組實例化；`if` 是這一顆硬體實例名稱；`&&` 是邏輯 AND：兩個條件都成立才為真。
// [逐行教學 L004][用途] 檢查 `tick_move && enable` 以決定資料/狀態要走哪一條路徑；把 `else` 子模組放進目前模組並與內部訊號連線。
  else if(tick_move && enable) begin
// [逐行教學 L005][語法] `if (direction_down)` 是條件分支：條件為 1 才執行後續敘述。
// [逐行教學 L005][用途] 檢查 `direction_down` 以決定資料/狀態要走哪一條路徑。
   if(direction_down) begin
// [逐行教學 L006][語法] `if (pos==5)` 是條件分支：條件為 1 才執行後續敘述；`else` 是前面條件都不成立時執行的備援分支；`direction_down <= ...`
// [逐行教學 L006][語法] 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`pos <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`1'b0` = 1-bit
// [逐行教學 L006][語法] 二進位常數；`1'b1` = 1-bit 二進位常數；`==` 是相等比較，結果為 1 或 0。
// [逐行教學 L006][用途] 檢查 `pos==5` 以決定資料/狀態要走哪一條路徑；更新 `direction_down`為 0/關閉或初始值；更新 `pos`，下一值由 `4` 計算；更新 `pos`為舊值
// [逐行教學 L006][用途] +1，完成向上計數。
    if(pos==5) begin direction_down<=1'b0;pos<=4;end else pos<=pos+1'b1;
// [逐行教學 L007][語法] `else` 是前面條件都不成立時執行的備援分支；`end else begin` 先結束前一分支，再開始 else 的多敘述分支。
// [逐行教學 L007][用途] 完成目前模組資料路徑或控制流程中的一個步驟。
   end else begin
// [逐行教學 L008][語法] `if (pos==0)` 是條件分支：條件為 1 才執行後續敘述；`else` 是前面條件都不成立時執行的備援分支；`direction_down <= ...`
// [逐行教學 L008][語法] 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`pos <= ...` 使用非阻塞賦值；常用於時序邏輯，先用舊值計算、事件結束時一起更新；`1'b1` = 1-bit
// [逐行教學 L008][語法] 二進位常數；`1'b1` = 1-bit 二進位常數；`==` 是相等比較，結果為 1 或 0。
// [逐行教學 L008][用途] 檢查 `pos==0` 以決定資料/狀態要走哪一條路徑；更新 `direction_down`，下一值由 `1'b1` 計算；更新 `pos`，下一值由 `1` 計算；更新 `pos`為舊值
// [逐行教學 L008][用途] -1，完成向下計數。
    if(pos==0) begin direction_down<=1'b1;pos<=1;end else pos<=pos-1'b1;
// [逐行教學 L009][語法] `end` 結束最近一個 `begin` 區塊。
// [逐行教學 L009][用途] 關閉目前條件、時序或組合邏輯區塊。
   end
// [逐行教學 L010][語法] `end` 結束最近一個 `begin` 區塊。
// [逐行教學 L010][用途] 關閉目前條件、時序或組合邏輯區塊。
  end
// [逐行教學 L011][語法] `end` 結束最近一個 `begin` 區塊。
// [逐行教學 L011][用途] 關閉目前條件、時序或組合邏輯區塊。
 end
// [逐行教學 L012][語法] `endmodule` 與前面的 `module` 配對，結束模組定義。
// [逐行教學 L012][用途] 結束 `flow3` 的 RTL 描述。
endmodule
