// [教學註解] 功能：掃描索引產生器：循環產生目前要顯示的列/行索引。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module idx_gen(clk, rst, idx);
    // [教學註解] 輸入埠：clk=系統時脈；rst=系統重置。
    input clk, rst;
    // [教學註解] 輸出埠：idx=目前掃描列索引。
    output [6:0] idx;
    // [教學註解] 程序賦值暫存型訊號(reg)：idx=目前掃描列索引。
    reg [6:0] idx;
    
    // [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
    always @(posedge clk or posedge rst) begin
        // [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
        if (rst)
            idx <= 7'd88; // 初始位址設在最底端 (準備顯示9)
        else if (idx == 7'd0) 
            idx <= 7'd88; // 捲動到 0 消失後，重置回 88 繼續循環
        else
            idx <= idx - 7'd1; // 【關鍵修改】每次減1，產生往下倒退捲動的效果
    end
endmodule