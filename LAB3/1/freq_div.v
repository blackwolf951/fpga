// [教學註解] 檔案：freq_div.v
// [教學註解] 模組：freq_div
// [教學註解] 功能：時脈分頻器：利用二進位計數器的高位元，將輸入時脈降低為較慢的時脈供後級電路使用。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module freq_div(clk_in, reset, clk_out);
// [教學註解] 參數(parameter)：讓常數可以在實例化時調整，用來控制位寬、分頻比或狀態設定。
parameter exp = 20;   
// [教學註解] 輸入埠：clk_in=輸入時脈；reset=系統重置。
input clk_in, reset;
// [教學註解] 輸出埠：clk_out=分頻後時脈。
output clk_out;
// [教學註解] 程序賦值暫存型訊號(reg)：宣告此區塊中使用的訊號與位元寬度。
reg[exp-1:0] divider;
integer i;
// [教學註解] 連續指定(assign)：描述組合邏輯連線，右式改變時左式會立即重新計算。
assign clk_out= divider[exp-1];
// [教學註解] 時序邏輯：在時脈邊緣更新狀態；reset/rst 也列在敏感度表中，所以是非同步重置。
always@ (posedge clk_in or posedge reset)	//正緣觸發
begin
// [教學註解] 重置判斷：重置成立時先把暫存器帶回已知初始狀態，避免上電後狀態不確定。
if(reset)
// [教學註解] for 迴圈在綜合時會展開成硬體操作；這裡常用來一次初始化多個位元。
for(i=0; i < exp; i=i+1)
divider[i] = 1'b0;
else
// [教學註解] 計數 +1：每次有效時脈事件讓目前數值增加一。
divider = divider+ 1'b1;
end
endmodule // <--- ADDED THIS LINE

