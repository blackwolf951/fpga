// [教學註解] 檔案：bcd_to_seg7.v
// [教學註解] 模組：bcd_to_seg7
// [教學註解] 功能：BCD 轉七段顯示解碼器：把 4-bit 數字代碼轉成 a~g 七個 LED 段的點亮組合。
// [教學註解] 閱讀方式：先看 I/O → 再看組合邏輯(assign/always @*) → 最後看時序邏輯(posedge)。
// [教學註解] 本次僅新增說明註解，不修改原本 Verilog 程式敘述與接線。
// ============================================================================
module bcd_to_seg7(bcd_in, seg7);
// [教學註解] 輸入埠：bcd_in=4-bit BCD 輸入。
input[3:0] bcd_in;
// [教學註解] 輸出埠：seg7=七段顯示輸出。
output[6:0] seg7;
// [教學註解] 程序賦值暫存型訊號(reg)：seg7=七段顯示輸出。
reg[6:0] seg7;
// [教學註解] 組合邏輯 always：敏感度表中的訊號改變時重新執行此區塊。
always@ (bcd_in) begin
	// [教學註解] case 多路選擇：依目前輸入/狀態選擇對應的輸出資料。
	case(bcd_in) // abcdefg
		4'b0000: seg7 = 7'b1111110; // 0
		4'b0001: seg7 = 7'b0110000; // 1
		4'b0010: seg7 = 7'b1101101; // 2
		4'b0011: seg7 = 7'b1111001; // 3
		4'b0100: seg7 = 7'b0110011; // 4
		4'b0101: seg7 = 7'b1011011; // 5
		4'b0110: seg7 = 7'b1011111; // 6
		4'b0111: seg7 = 7'b1110000; // 7
		4'b1000: seg7 = 7'b1111111; // 8
		4'b1001: seg7 = 7'b1111011; // 9
		// [教學註解] default 提供未列舉情況的安全輸出，組合邏輯中可避免輸出沒有被指定而推導出 latch。
		default: seg7 = 7'b0000000;
	endcase
end
endmodule
